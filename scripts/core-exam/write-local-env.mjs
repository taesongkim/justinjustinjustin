import { execFile } from "node:child_process";
import { chmod, writeFile } from "node:fs/promises";
import path from "node:path";
import process from "node:process";
import { promisify } from "node:util";

const execFileAsync = promisify(execFile);
const outputPath = path.join(process.cwd(), ".env.development.local");

const { stdout } = await execFileAsync("supabase", ["status", "-o", "env"], {
  maxBuffer: 1024 * 1024,
});

const localValues = new Map();
for (const line of stdout.split(/\r?\n/)) {
  const match = line.match(/^([A-Z_]+)=(.*)$/);
  if (!match) continue;
  localValues.set(
    match[1],
    match[2].trim().replace(/^"|"$/g, ""),
  );
}

const apiUrl = localValues.get("API_URL");
const anonKey = localValues.get("ANON_KEY");

if (!apiUrl || !anonKey) {
  throw new Error("Local Supabase status did not provide API_URL and ANON_KEY");
}

const contents = [
  "# Generated by npm run core-exam:local-env. Do not commit.",
  `NEXT_PUBLIC_SUPABASE_URL=${apiUrl}`,
  `NEXT_PUBLIC_SUPABASE_ANON_KEY=${anonKey}`,
  "",
].join("\n");

await writeFile(outputPath, contents, { mode: 0o600 });
await chmod(outputPath, 0o600);

console.log(
  `Wrote local public client configuration to ${path.basename(outputPath)}.`,
);
console.log("No service-role, database, JWT, or storage secrets were written.");
